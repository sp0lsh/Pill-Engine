//! Rust bindings generated from slangc's reflection JSON (`<shader>.reflect.json`, written by
//! `HlslToWgsl`): per shader a module with its bind group layout entries and named binding slots,
//! plus one `structs` module with a `#[repr(C)]` mirror of every uniform / storage struct, padded
//! to the offsets slangc reports for WGSL.
//!
//! The generated code expects `Binding { group: u32, binding: u32 }` in its parent module.
//!
//! Binding properties the shader can't express come from `include/bindings.hlsl` attributes:
//! `[Unfilterable]`, `[Depth]` (textures), `[Comparison]`, `[NonFiltering]` (samplers),
//! `[DynamicOffset]` (uniform buffers).

use std::collections::BTreeMap;
use std::fmt::Write as _;

use anyhow::{bail, Context, Result};
use serde_json::Value;

/// One field of a generated struct; padding fields have `name` `_pad<offset>`.
#[derive(Debug, PartialEq)]
struct Field {
    name: String,
    rust_type: String,
}

#[derive(Debug, PartialEq)]
struct StructDef {
    fields: Vec<Field>,
    size: u32,
    align: u32,
}

/// Rust layout of a reflected type: type name, alignment and size in bytes.
struct TypeLayout {
    rust_type: String,
    align: u32,
    size: u32,
}

/// Structs collected across shaders: name → (definition, first shader defining it).
type Structs = BTreeMap<String, (StructDef, String)>;

/// Rust source for `shaders`: (file stem, reflection JSON) pairs, e.g.
/// `("tonemap_fragment", "{...}")`.
pub fn generate(shaders: &[(String, String)]) -> Result<String> {
    let mut structs = Structs::new();
    let mut modules = String::new();
    for (stem, json) in shaders {
        let reflection: Value = serde_json::from_str(json)
            .with_context(|| format!("{stem}: invalid reflection JSON"))?;
        modules += &shader_module(stem, &reflection, &mut structs)
            .with_context(|| format!("shader bindings of {stem}"))?;
    }

    let mut out = String::new();
    out += "// Generated by pill_assets::shader_bindings from slangc reflection. Do not edit.\n";
    out += "#[allow(dead_code)]\npub mod structs {\n";
    for (name, (def, _)) in &structs {
        out += "    #[repr(C)]\n    #[derive(Copy, Clone, bytemuck::Pod, bytemuck::Zeroable)]\n";
        let _ = writeln!(out, "    pub struct {name} {{");
        for field in &def.fields {
            let _ = writeln!(
                out,
                "        pub {}: {},",
                rust_ident(&field.name),
                field.rust_type
            );
        }
        out += "    }\n";
        let _ = writeln!(
            out,
            "    const _: () = assert!(std::mem::size_of::<{name}>() == {});",
            def.size
        );
    }
    out += "}\n";
    out += &modules;
    Ok(out)
}

fn shader_module(stem: &str, reflection: &Value, structs: &mut Structs) -> Result<String> {
    let stage = if stem.ends_with("_vertex") {
        "VERTEX"
    } else if stem.ends_with("_fragment") {
        "FRAGMENT"
    } else if stem.ends_with("_compute") {
        "COMPUTE"
    } else {
        bail!("no stage suffix");
    };

    let mut constants = String::new();
    // group → (binding, entry type source)
    let mut groups: BTreeMap<u32, BTreeMap<u32, String>> = BTreeMap::new();
    let parameters = reflection["parameters"]
        .as_array()
        .context("no `parameters`")?;
    for parameter in parameters {
        let name = parameter["name"]
            .as_str()
            .context("parameter without name")?;
        let binding = &parameter["binding"];
        let index = binding["index"].as_u64().context("binding without index")? as u32;
        match binding["kind"].as_str() {
            Some("specializationConstant") => {
                let _ = writeln!(
                    constants,
                    "    /// Pipeline-overridable constant `{name}` (`@id({index})`)\n    pub const {}: &str = \"{index}\";",
                    name.to_uppercase()
                );
                continue;
            }
            Some("descriptorTableSlot") => {}
            other => bail!("{name}: unsupported binding kind {other:?}"),
        }
        let group = binding["space"].as_u64().unwrap_or(0) as u32;
        let attributes: Vec<&str> = parameter["userAttribs"]
            .as_array()
            .map(|list| list.iter().filter_map(|a| a["name"].as_str()).collect())
            .unwrap_or_default();
        let ty = binding_type(stem, name, parameter, &attributes, structs)?;
        if groups.entry(group).or_default().insert(index, ty).is_some() {
            bail!("{name}: binding {index} of group {group} declared twice");
        }
        let _ = writeln!(
            constants,
            "    pub const {}: Binding = Binding {{ group: {group}, binding: {index} }};",
            name.to_uppercase()
        );
    }

    let mut out = String::new();
    let _ = writeln!(out, "#[allow(dead_code)]\npub mod {stem} {{");
    out += "    use super::Binding;\n";
    let _ = writeln!(
        out,
        "    pub const STAGE: wgpu::ShaderStages = wgpu::ShaderStages::{stage};"
    );
    out += &constants;
    out += "    /// Bind group layout entries per group (index = group), visible to `STAGE`\n";
    out += "    pub fn layout() -> Vec<Vec<wgpu::BindGroupLayoutEntry>> {\n        vec![\n";
    let group_count = groups.keys().next_back().map_or(0, |last| last + 1);
    for group in 0..group_count {
        out += "            vec![\n";
        for (binding, ty) in groups.get(&group).into_iter().flatten() {
            let _ = writeln!(
                out,
                "                wgpu::BindGroupLayoutEntry {{ binding: {binding}, visibility: STAGE, ty: {ty}, count: None }},"
            );
        }
        out += "            ],\n";
    }
    out += "        ]\n    }\n}\n";
    Ok(out)
}

/// `wgpu::BindingType` source of one parameter.
fn binding_type(
    stem: &str,
    name: &str,
    parameter: &Value,
    attributes: &[&str],
    structs: &mut Structs,
) -> Result<String> {
    let ty = &parameter["type"];
    let has = |attribute: &str| attributes.contains(&attribute);
    Ok(match ty["kind"].as_str() {
        Some("constantBuffer") => {
            let element = &ty["elementType"];
            if element["kind"] == "struct" {
                type_layout(stem, element, structs)?;
            }
            format!(
                "wgpu::BindingType::Buffer {{ ty: wgpu::BufferBindingType::Uniform, has_dynamic_offset: {}, min_binding_size: None }}",
                has("DynamicOffset")
            )
        }
        Some("samplerState") => {
            let kind = if has("Comparison") {
                "Comparison"
            } else if has("NonFiltering") {
                "NonFiltering"
            } else {
                "Filtering"
            };
            format!("wgpu::BindingType::Sampler(wgpu::SamplerBindingType::{kind})")
        }
        Some("resource") => {
            let access = ty["access"].as_str().unwrap_or("read");
            let result = &ty["resultType"];
            match ty["baseShape"].as_str() {
                Some("structuredBuffer") => {
                    type_layout(stem, result, structs)?;
                    format!(
                        "wgpu::BindingType::Buffer {{ ty: wgpu::BufferBindingType::Storage {{ read_only: {} }}, has_dynamic_offset: false, min_binding_size: None }}",
                        access == "read"
                    )
                }
                Some("texture2D") => {
                    let dimension = if ty["array"].as_bool().unwrap_or(false) {
                        "D2Array"
                    } else {
                        "D2"
                    };
                    if access == "read" {
                        let scalar = if result["kind"] == "scalar" {
                            &result["scalarType"]
                        } else {
                            &result["elementType"]["scalarType"]
                        };
                        let sample_type = match scalar.as_str() {
                            _ if has("Depth") => "Depth".to_owned(),
                            Some("float32") => {
                                format!("Float {{ filterable: {} }}", !has("Unfilterable"))
                            }
                            Some("uint32") => "Uint".to_owned(),
                            Some("int32") => "Sint".to_owned(),
                            other => bail!("{name}: unsupported texel type {other:?}"),
                        };
                        format!(
                            "wgpu::BindingType::Texture {{ sample_type: wgpu::TextureSampleType::{sample_type}, view_dimension: wgpu::TextureViewDimension::{dimension}, multisampled: false }}"
                        )
                    } else {
                        let format = match parameter["format"].as_str() {
                            Some("rgba16f") => "Rgba16Float",
                            Some("rgba32f") => "Rgba32Float",
                            Some("r32f") => "R32Float",
                            Some("rgba8") => "Rgba8Unorm",
                            other => bail!("{name}: unsupported storage texture format {other:?}"),
                        };
                        let storage_access = if access == "write" {
                            "WriteOnly"
                        } else {
                            "ReadWrite"
                        };
                        format!(
                            "wgpu::BindingType::StorageTexture {{ access: wgpu::StorageTextureAccess::{storage_access}, format: wgpu::TextureFormat::{format}, view_dimension: wgpu::TextureViewDimension::{dimension} }}"
                        )
                    }
                }
                other => bail!("{name}: unsupported resource shape {other:?}"),
            }
        }
        other => bail!("{name}: unsupported parameter type {other:?}"),
    })
}

/// Rust layout of `ty`; structs are added to `structs` (and checked against an earlier
/// definition of the same name).
fn type_layout(stem: &str, ty: &Value, structs: &mut Structs) -> Result<TypeLayout> {
    Ok(match ty["kind"].as_str() {
        Some("scalar") => {
            let rust_type = scalar_type(&ty["scalarType"])?;
            TypeLayout {
                rust_type: rust_type.to_owned(),
                align: 4,
                size: 4,
            }
        }
        Some("vector") => {
            let scalar = scalar_type(&ty["elementType"]["scalarType"])?;
            let count = ty["elementCount"]
                .as_u64()
                .context("vector without count")? as u32;
            TypeLayout {
                rust_type: format!("[{scalar}; {count}]"),
                align: if count == 2 { 8 } else { 16 },
                size: 4 * count,
            }
        }
        Some("matrix") => {
            let rows = ty["rowCount"].as_u64();
            let columns = ty["columnCount"].as_u64();
            if rows != Some(4) || columns != Some(4) || ty["elementType"]["scalarType"] != "float32"
            {
                bail!("unsupported matrix {rows:?}x{columns:?}");
            }
            TypeLayout {
                rust_type: "[[f32; 4]; 4]".to_owned(),
                align: 16,
                size: 64,
            }
        }
        Some("array") => {
            let element = type_layout(stem, &ty["elementType"], structs)?;
            let count = ty["elementCount"].as_u64().context("array without count")? as u32;
            let stride = ty["uniformStride"]
                .as_u64()
                .map_or(element.size, |stride| stride as u32);
            if stride != element.size {
                bail!(
                    "array of {} has stride {stride}, element size {}",
                    element.rust_type,
                    element.size
                );
            }
            TypeLayout {
                rust_type: format!("[{}; {count}]", element.rust_type),
                align: element.align,
                size: stride * count,
            }
        }
        Some("struct") => {
            let name = ty["name"].as_str().context("struct without name")?;
            let def = struct_def(stem, ty, structs)?;
            let layout = TypeLayout {
                rust_type: name.to_owned(),
                align: def.align,
                size: def.size,
            };
            match structs.get(name) {
                Some((existing, first)) if *existing != def => {
                    bail!("struct {name} differs between {first} and {stem}")
                }
                Some(_) => {}
                None => {
                    structs.insert(name.to_owned(), (def, stem.to_owned()));
                }
            }
            layout
        }
        other => bail!("unsupported type kind {other:?}"),
    })
}

/// Fields of a reflected struct in offset order, with `_pad<offset>` fields over the gaps.
fn struct_def(stem: &str, ty: &Value, structs: &mut Structs) -> Result<StructDef> {
    let mut members = Vec::new();
    for field in ty["fields"].as_array().context("struct without fields")? {
        let name = field["name"].as_str().context("field without name")?;
        let offset = field["binding"]["offset"]
            .as_u64()
            .with_context(|| format!("field {name} without offset"))? as u32;
        let layout = type_layout(stem, &field["type"], structs)?;
        members.push((offset, name.to_owned(), layout));
    }
    members.sort_by_key(|(offset, _, _)| *offset);

    let align = members
        .iter()
        .map(|(_, _, layout)| layout.align)
        .max()
        .unwrap_or(4);
    let end = members
        .iter()
        .map(|(offset, _, layout)| offset + layout.size)
        .max()
        .unwrap_or(0);
    let size = end.div_ceil(align) * align;

    let mut fields = Vec::new();
    let mut cursor = 0;
    let pad_to = |fields: &mut Vec<Field>, cursor: u32, target: u32| {
        if target > cursor {
            fields.push(Field {
                name: format!("_pad{cursor}"),
                rust_type: format!("[u32; {}]", (target - cursor) / 4),
            });
        }
    };
    for (offset, name, layout) in members {
        if offset < cursor {
            bail!("field {name} at {offset} overlaps the previous field");
        }
        pad_to(&mut fields, cursor, offset);
        cursor = offset + layout.size;
        fields.push(Field {
            name,
            rust_type: layout.rust_type,
        });
    }
    pad_to(&mut fields, cursor, size);
    Ok(StructDef {
        fields,
        size,
        align,
    })
}

fn scalar_type(scalar: &Value) -> Result<&'static str> {
    Ok(match scalar.as_str() {
        Some("float32") => "f32",
        Some("uint32") => "u32",
        Some("int32") => "i32",
        other => bail!("unsupported scalar type {other:?}"),
    })
}

/// `name`, as a raw identifier when it is a Rust keyword.
fn rust_ident(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn",
        "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
        "return", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
        "while", "async", "await", "dyn", "box", "final", "macro", "override", "priv", "typeof",
        "unsized", "virtual", "yield", "try",
    ];
    if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_owned()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scalar(name: &str, scalar: &str, offset: u32) -> String {
        format!(
            r#"{{"name": "{name}", "type": {{"kind": "scalar", "scalarType": "{scalar}"}}, "binding": {{"kind": "uniform", "offset": {offset}, "size": 4}}}}"#
        )
    }

    fn uniform_shader(struct_name: &str, fields: &[String]) -> String {
        format!(
            r#"{{"parameters": [{{"name": "params", "binding": {{"kind": "descriptorTableSlot", "index": 2}},
                "type": {{"kind": "constantBuffer", "elementType": {{"kind": "struct", "name": "{struct_name}", "fields": [{}]}}}}}}]}}"#,
            fields.join(",")
        )
    }

    fn shader(stem: &str, json: String) -> (String, String) {
        (stem.to_owned(), json)
    }

    #[test]
    fn struct_gap_at_8_padded_to_offset_and_alignment() {
        let json = uniform_shader(
            "Params",
            &[scalar("a", "uint32", 0), scalar("b", "float32", 12)],
        );
        let out = generate(&[shader("x_fragment", json)]).unwrap();
        assert!(out.contains("pub a: u32,\n        pub _pad4: [u32; 2],\n        pub b: f32,"));
        assert!(out.contains("size_of::<Params>() == 16"));
    }

    #[test]
    fn uniform_slot_2_group_0_entry_and_const() {
        let json = uniform_shader("Params", &[scalar("a", "float32", 0)]);
        let out = generate(&[shader("x_fragment", json)]).unwrap();
        assert!(out.contains("pub const PARAMS: Binding = Binding { group: 0, binding: 2 };"));
        assert!(out.contains("binding: 2, visibility: STAGE, ty: wgpu::BindingType::Buffer { ty: wgpu::BufferBindingType::Uniform"));
        assert!(out.contains("wgpu::ShaderStages::FRAGMENT"));
    }

    #[test]
    fn unfilterable_texture_in_space_1_filterable_false_group_1() {
        let json = r#"{"parameters": [{"name": "depth", "userAttribs": [{"name": "Unfilterable", "arguments": []}],
            "binding": {"kind": "descriptorTableSlot", "space": 1, "index": 3},
            "type": {"kind": "resource", "baseShape": "texture2D", "resultType": {"kind": "scalar", "scalarType": "float32"}}}]}"#;
        let out = generate(&[shader("x_fragment", json.to_owned())]).unwrap();
        assert!(out.contains("Binding { group: 1, binding: 3 }"));
        assert!(out.contains("sample_type: wgpu::TextureSampleType::Float { filterable: false }"));
        // Group 0 is empty
        assert!(out.contains("vec![\n            vec![\n            ],\n            vec![\n"));
    }

    #[test]
    fn comparison_sampler_attribute_comparison_binding() {
        let json = r#"{"parameters": [{"name": "s", "userAttribs": [{"name": "Comparison", "arguments": []}],
            "binding": {"kind": "descriptorTableSlot", "index": 0}, "type": {"kind": "samplerState"}}]}"#;
        let out = generate(&[shader("x_fragment", json.to_owned())]).unwrap();
        assert!(out.contains("wgpu::SamplerBindingType::Comparison"));
    }

    #[test]
    fn same_struct_name_different_layout_fails() {
        let a = uniform_shader("Camera", &[scalar("a", "float32", 0)]);
        let b = uniform_shader("Camera", &[scalar("b", "float32", 0)]);
        let error = generate(&[shader("a_vertex", a), shader("b_vertex", b)]).unwrap_err();
        assert!(
            format!("{error:#}").contains("struct Camera differs between a_vertex and b_vertex")
        );
    }

    #[test]
    fn specialization_constant_override_id() {
        let json = r#"{"parameters": [{"name": "ALPHA_TEST", "binding": {"kind": "specializationConstant", "index": 0},
            "type": {"kind": "scalar", "scalarType": "bool"}}]}"#;
        let out = generate(&[shader("x_fragment", json.to_owned())]).unwrap();
        assert!(out.contains("pub const ALPHA_TEST: &str = \"0\";"));
    }
}
